export function lucideNode(icon: string): IconNode | undefined {
  return icon.startsWith(LUCIDE_PREFIX) ? NODES[icon.slice(LUCIDE_PREFIX.length)] : undefined;
}

function pathOf(tag: string, a: Record<string, string | number>): Path2D | null {
  const n = (k: string) => Number(a[k] ?? 0);
  const p = new Path2D();
  if (tag === "path") return new Path2D(String(a.d));
  if (tag === "circle") p.arc(n("cx"), n("cy"), n("r"), 0, Math.PI * 2);
  else if (tag === "ellipse") p.ellipse(n("cx"), n("cy"), n("rx"), n("ry"), 0, 0, Math.PI * 2);
  else if (tag === "rect") p.roundRect(n("x"), n("y"), n("width"), n("height"), n("rx"));
  else if (tag === "line") {
    p.moveTo(n("x1"), n("y1"));
    p.lineTo(n("x2"), n("y2"));
  } else if (tag === "polyline" || tag === "polygon") {
    const pts = String(a.points).trim().split(/[s,]+/).map(Number);
    for (let i = 0; i + 1 < pts.length; i += 2) {
      if (i === 0) p.moveTo(pts[i], pts[i + 1]);
      else p.lineTo(pts[i], pts[i + 1]);
    }
    if (tag === "polygon") p.closePath();
  } else return null;
  return p;
}

/** Dibuja el ícono con trazo del color de la pieza (sin fuente emoji: el PNG se exporta sin problema). */
export type Ink = (x0: number, y0: number, x1: number, y1: number) => string | CanvasGradient;

export function drawLucide(ctx: CanvasRenderingContext2D, icon: string, cx: number, cy: number, size: number, ink: Ink) {
  const node = lucideNode(icon);
  if (!node) return;
  const k = size / 24;
  ctx.translate(cx - size / 2, cy - size / 2);
  ctx.scale(k, k);
  ctx.shadowBlur /= k;
  ctx.shadowOffsetX /= k;
  ctx.shadowOffsetY /= k;
  ctx.strokeStyle = ink(0, 0, 24, 24);
  ctx.lineWidth = 2;
  ctx.lineCap = "round";
  ctx.lineJoin = "round";
  for (const [tag, attrs] of node) {
    const path = pathOf(tag, attrs);
    if (path) ctx.stroke(path);
  }
}
